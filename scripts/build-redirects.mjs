#!/usr/bin/env node
// Compiles content/redirect-map.csv → apps/web/lib/redirects.generated.ts
//
// WHY THIS EXISTS (VG-002 / blueprint §16, §17.2)
// middleware.ts previously carried three hand-typed redirects under a comment
// claiming the map was "compiled from content/redirect-map.csv at build time".
// It was not. The CSV held 57 rows. On DNS cutover the other 54 legacy URLs
// would have 301'd nowhere, 404'd, and dropped their link equity — the single
// most expensive silent failure available on a migration.
//
// The fix is not to paste 57 entries by hand; that reintroduces the same drift
// one edit later. The CSV is the artefact, this script is the only writer, and
// redirects.test.ts asserts row-count parity so the two can never diverge again.
//
// Run: node scripts/build-redirects.mjs   (wired to apps/web prebuild)

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = resolve(root, 'content/redirect-map.csv')
const OUT = resolve(root, 'apps/web/lib/redirects.generated.ts')

/** @returns {{from: string, to: string, status: number}[]} */
export function parseRedirectCsv(csv) {
  const rows = []
  const seen = new Map()
  const lines = csv.split(/\r?\n/)

  lines.forEach((raw, i) => {
    const line = raw.trim()
    if (!line) return
    if (line.startsWith('#')) return // section comment
    if (i === 0 && line.startsWith('legacy_path')) return // header

    const parts = line.split(',')
    if (parts.length < 3) {
      throw new Error(`redirect-map.csv:${i + 1} — expected 3 columns, got ${parts.length}: "${line}"`)
    }
    const [from, to, statusRaw] = parts.map((p) => p.trim())
    const status = Number(statusRaw)

    if (!from.startsWith('/')) throw new Error(`redirect-map.csv:${i + 1} — legacy_path must start with "/": "${from}"`)
    if (!to.startsWith('/')) throw new Error(`redirect-map.csv:${i + 1} — destination must start with "/": "${to}"`)
    if (status !== 301 && status !== 308) {
      throw new Error(`redirect-map.csv:${i + 1} — status must be 301 or 308, got "${statusRaw}"`)
    }

    // A row pointing at itself is an infinite redirect at the edge. The CSV ships
    // one ("/,/,301") which is harmless as data and fatal as a rule. Drop it here
    // rather than in middleware, so the reason is recorded once.
    if (from === to) return

    if (seen.has(from)) {
      throw new Error(
        `redirect-map.csv:${i + 1} — duplicate legacy_path "${from}" (first seen line ${seen.get(from)})`
      )
    }
    seen.set(from, i + 1)
    rows.push({ from, to, status })
  })

  return rows
}

/** Redirect chains cost crawl budget and are flagged by every audit tool. */
function assertNoChains(rows) {
  const sources = new Set(rows.map((r) => r.from))
  const chains = rows.filter((r) => sources.has(r.to))
  if (chains.length) {
    const detail = chains.map((c) => `${c.from} → ${c.to} (which itself redirects)`).join('\n  ')
    throw new Error(`redirect-map.csv — ${chains.length} redirect chain(s):\n  ${detail}`)
  }
}

function main() {
  const rows = parseRedirectCsv(readFileSync(SRC, 'utf8'))
  assertNoChains(rows)

  const entries = rows
    .map((r) => `  ${JSON.stringify(r.from)}: { to: ${JSON.stringify(r.to)}, status: ${r.status} },`)
    .join('\n')

  const out = `// GENERATED by scripts/build-redirects.mjs — do not edit.
// Source of truth: content/redirect-map.csv. Edit that, then rebuild.
// Parity between the CSV and this file is asserted by apps/web/lib/redirects.test.ts.

export interface LegacyRedirect {
  to: string
  status: 301 | 308
}

export const LEGACY_REDIRECT_COUNT = ${rows.length}

export const LEGACY_REDIRECTS: Record<string, LegacyRedirect> = {
${entries}
}
`

  mkdirSync(dirname(OUT), { recursive: true })
  writeFileSync(OUT, out)
  console.log(`build-redirects: compiled ${rows.length} redirects → apps/web/lib/redirects.generated.ts`)
}

if (import.meta.url === `file://${process.argv[1]}`) main()
